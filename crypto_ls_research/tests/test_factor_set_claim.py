def test_rev_short_trap_cites_both_constructions():
    """Both constructions, not only the standalone book."""
    body = _trap_body(spec.FACTOR_NAMES)
    assert "30_reversal_book.csv" in body, "standalone-book evidence must be cited"
    assert "34_neutralisation_study.csv" in body, (
        "the composite counter-evidence must be cited: without it the entry reads as "
        "'rev_short is bad, never put it in the subset', which the project's own "
        "artifact contradicts")
    assert "独立 book" in body and "复合分数" in body


def test_rev_short_trap_does_not_quote_orphan_numbers():
    """The gross-Sharpe list that matched no artifact must not come back."""
    body = _trap_body(spec.FACTOR_NAMES)
    for orphan in ("0.569", "0.976", "0.966", "0.832", "0.859"):
        assert orphan not in body, (
            f"{orphan} came from a gross-Sharpe list that matches no artifact on disk. "
            f"Cite the artifact and the column name instead of embedding the numbers.")


def test_rev_short_trap_composite_numbers_match_the_artifact():
    """The load-bearing pair must be readable out of the artifact, not remembered."""
    t = _read_table("34_neutralisation_study.csv")
    four = float(t.loc[t.label == "spec4(mom,flow,rp,hr)|neutralize=False",
                       "Sharpe"].iloc[0])
    five = float(t.loc[t.label == "all5+rev_short|neutralize=False", "Sharpe"].iloc[0])
    assert five > four, (
        "the artifact no longer supports 'adding rev_short as a composite component "
        "raises Sharpe' -- the trap wording has to change with it")
    body = _trap_body(spec.FACTOR_NAMES)
    # The *pair*, not the individual numbers: "1.937" on its own is also a substring of
    # "1.9375" and of the haircut sentence, so a loose check passes on a mutated text.
    assert _pair_in(body, four, five), (
        f"trap text must quote the artifact's {four:.3f} / {five:.3f} as a pair "
        f"(from 34_neutralisation_study.csv)")


def test_rev_short_trap_does_not_revive_the_cross_tag_haircut_claim():
    """Reason (3) used to compare this tag's Sharpe against the *previous* tag's haircut.

    `16_multiplicity_summary.csv` is regenerated by every run, so `v4_1d`'s
    `deflated_haircut` and `v5_1d_all5`'s Sharpe come from different samples.  The old
    sentence ("1.9377 beats the project's own haircut 1.9375 by 0.0002") read as a pass
    while being directionally wrong: per tag, neither basis clears its own haircut, and
    the five-factor set is the *closer* of the two.  It was deleted rather than reworded,
    and this pins that it does not come back in the old form.
    """
    stale = float(_read_table("16_multiplicity_summary.csv",
                              tag=PREV_TAG)["deflated_haircut"].iloc[0])
    body = _trap_body(spec.FACTOR_NAMES)
    assert f"{stale:.4f}" not in body, (
        f"{stale:.4f} is {PREV_TAG}'s deflated_haircut, not {TAG}'s -- quoting it beside "
        f"this tag's Sharpe is exactly the cross-tag comparison the promotion corrected. "
        f"If a haircut is cited, cite the one from artifacts/{TAG}/tables/.")


def test_rev_short_trap_quotes_the_fold_means_from_the_artifact():
    """Reason (2) is a walk-forward mean: recompute it, so a rebuild turns this red
    instead of leaving a stale number in the console."""
    f = _read_table("34b_neutralisation_folds.csv")
    two_cfg, five_cfg = "v2(rp,hr)|neutralize=False", "all5+rev_short|neutralize=False"
    for cfg in (two_cfg, five_cfg):
        assert len(f[f.config == cfg]) > 0, f"{cfg} missing from the fold table"
    two = f[f.config == two_cfg]
    five = f[f.config == five_cfg]
    assert five["test_sharpe"].mean() < two["test_sharpe"].mean(), (
        "the artifact no longer supports 'the five-factor OOS mean is not better'")
    assert five["train_sharpe"].mean() > two["train_sharpe"].mean(), (
        "the artifact no longer supports 'the five-factor TRAIN mean is higher'")
    body = _trap_body(spec.FACTOR_NAMES)
    # Pairs, not lone numbers -- see the note in the composite test above.
    for a, b in ((five["test_sharpe"].mean(), two["test_sharpe"].mean()),
                 (five["train_sharpe"].mean(), two["train_sharpe"].mean())):
        assert _pair_in(body, a, b), (
            f"trap must quote the recomputed fold means {a:.3f} / {b:.3f} as a pair")


# ---------------------------------------------------------------------------
# 3. the finding itself: better at 1 day, worse at 3 days, and not a win-rate gain
# ---------------------------------------------------------------------------
def test_the_five_factor_gain_does_not_survive_the_other_grid():
    """The improvement is a property of the (factor set, grid) pair, not of the set."""
    g = _sharpe_by_label("factor_set_grid")
    assert g["all5(+rev_short)@1d"] > g["v2(rp,hr)@1d"], "no longer wins at 1 day"
    assert g["all5(+rev_short)@3d"] < g["v2(rp,hr)@3d"], (
        "the ordering no longer reverses at 3 days -- if the reversal really went away, "
        "the robustness verdict in FINDINGS Q32 has to be revisited")


def test_the_five_factor_gain_is_not_a_win_rate_gain():
    """闸门 22: the improvement is payoff asymmetry, not hit rate.

    The user's claim was specifically「胜率更好」.  It is **not decidable**: at the 1-day
    grid the three win rates are 51.62% / 50.91% / 51.43%, and with n ≈ 2097 days the
    standard error is ≈1.09pp, so the largest gap is 0.34σ.  This test pins the two
    halves of that statement -- the win rate does not separate the arms, and the profit
    factor does -- so a wording change in either direction has to come with evidence.
    """
    t = _read_table("exp_factor_set_grid.csv", tag="factor_set_grid")
    w = dict(zip(t["label"], t["win_rate_daily"]))
    pf = dict(zip(t["label"], t["profit_factor_daily"]))
    d_win = w["all5(+rev_short)@1d"] - w["v2(rp,hr)@1d"]
    assert abs(d_win) < 0.005, (
        f"the daily win rates now differ by {d_win:+.4f}, which is no longer inside the "
        f"≈1.1pp standard error -- 「胜率更好」would have become a real claim and the "
        f"preset/trap wording must be rewritten")
    assert pf["all5(+rev_short)@1d"] > pf["v2(rp,hr)@1d"], (
        "the gain has to show up in the profit factor if it is not in the win rate")


def test_the_five_factor_gain_is_not_the_equal_weight_degeneracy():
    """`construct.inverse_vol_weights` equal-weights the book whenever `cap*n <= 1`, and
    this project already measured that in a narrow cross-section equal weight *is* the
    risk control.  So 'the five-factor arm simply selects fewer names per side' is the
    first alternative explanation, and it has to stay excluded."""
    t = _read_table("exp_factor_set_grid.csv", tag="factor_set_grid")
    nl = dict(zip(t["label"], t["sel_n_long_med"]))
    eq = dict(zip(t["label"], t["frac_eqw_either"]))
    assert nl["all5(+rev_short)@1d"] == nl["v2(rp,hr)@1d"], (
        "selection width differs between the arms, so the comparison is confounded")
    assert eq["all5(+rev_short)@1d"] <= eq["v2(rp,hr)@1d"], (
        "the five-factor arm triggers the equal-weight fallback more often than the "
        "accepted arm -- the gain could be the sizing degeneracy, not factor information")
